// Rasterise the app icon, from lib/src/ui/mark_spec.dart.
//
//     make icons        (or: dart run tool/make_icons.dart)
//
// Run it after changing MarkSpec, and commit what it writes. The output is
// deterministic: the same spec produces byte-identical files, so a run that
// changes nothing shows up as nothing in `git status`.
//
// Why a generator and not a drawing program: the mark is four strokes on a
// rounded square, and it has to exist at eleven sizes across three platforms.
// Exporting those by hand is eleven chances to ship a stale one, and the
// smallest — 16 pixels, the Windows taskbar — is the one a general-purpose
// export pipeline does worst, because it downscales a large bitmap instead of
// drawing the shape at the size it will be seen.
//
// Everything here is drawn from signed distance fields and antialiased by
// coverage, which is why 16px comes out crisp. No image library is involved:
// PNG is a zlib stream of filtered scanlines, and ICO is a directory of PNGs,
// both of which are shorter to write than to depend on.
//
// Plain Dart, not Flutter — `dart:ui` would give us a Canvas but only inside a
// running engine, which is a poor trade for a build-time script.

import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;
import 'dart:typed_data';

import 'package:ddirc/src/ui/mark_spec.dart';

/// Windows wants every size in one file. 16 and 32 are the taskbar and the
/// title bar, 256 is the one Explorer shows in a large-icon view.
const _icoSizes = [16, 24, 32, 48, 64, 128, 256];

/// The notification area, at the four display scalings Windows offers: 16
/// pixels at 100%, then 125%, 150% and 200%. Windows picks from the file
/// rather than scaling, so an omitted size is a blurred icon, not a missing
/// one — which is the kind of fault nobody reports.
const _trayIcoSizes = [16, 20, 24, 32];

/// How much of a menu-bar template the glyph occupies.
///
/// The macOS tray image is the hash alone, with no field behind it, so it has
/// to be drawn larger than it is inside the app icon or it reads as a speck in
/// a 22-point slot. Derived from [MarkSpec.inset] rather than typed as a
/// number, so widening the glyph in the spec cannot silently shrink this.
const _templateScale = 0.86 / (1 - 2 * MarkSpec.inset);

/// Android's five densities, at 48dp for the legacy icon and 108dp for the
/// adaptive one.
const _androidDensities = {
  'mdpi': 1,
  'hdpi': 2, // 1.5, rounded up to keep every size an integer
  'xhdpi': 2,
  'xxhdpi': 3,
  'xxxhdpi': 4,
};

/// How much of a macOS icon's canvas the mark occupies.
///
/// Apple's grid puts a rounded-rectangle app icon at about four fifths of the
/// canvas, with the rest transparent margin, and the Dock lines every icon up
/// on that assumption. Full bleed would simply look bigger than its
/// neighbours.
const _macScale = 0.82;

/// How much of the adaptive foreground the mark occupies.
///
/// Android masks that canvas to whatever shape the launcher uses and can
/// animate it, so only the middle two thirds is guaranteed to survive. At this
/// scale the hash spans just under half the canvas — comfortably inside the
/// safe zone, and still the size of a normal launcher icon once masked.
const _foregroundScale = 0.80;

void main(List<String> args) {
  final root = Directory.current;
  if (!File('${root.path}/pubspec.yaml').existsSync()) {
    stderr.writeln('run this from the repository root');
    exit(2);
  }

  final written = <String, int>{};

  void write(String path, List<int> bytes) {
    final file = File(path);
    file.parent.createSync(recursive: true);
    file.writeAsBytesSync(bytes);
    written[path] = bytes.length;
  }

  // Windows: one .ico holding every size, drawn at each.
  write(
    'windows/runner/resources/app_icon.ico',
    ico([for (final size in _icoSizes) png(render(size), size, size)]),
  );

  // Android: the legacy launcher icon, and the adaptive one's foreground.
  for (final MapEntry(key: density, value: factor)
      in _androidDensities.entries) {
    final dir = 'android/app/src/main/res/mipmap-$density';
    final legacy = 48 * factor;
    final adaptive = 108 * factor;
    write('$dir/ic_launcher.png', png(render(legacy), legacy, legacy));
    write(
      '$dir/ic_launcher_foreground.png',
      png(
        render(adaptive, field: false, scale: _foregroundScale),
        adaptive,
        adaptive,
      ),
    );
  }

  // The adaptive icon itself: a flat field, and the glyph floating above it.
  // Generated rather than hand-written so the colour cannot drift from the
  // one the bitmaps are drawn in.
  write(
    'android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml',
    utf8.encode(
      '<?xml version="1.0" encoding="utf-8"?>\n'
      '<!-- Generated by tool/make_icons.dart. Do not edit. -->\n'
      '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
      '    <background android:drawable="@color/ic_launcher_background" />\n'
      '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
      '</adaptive-icon>\n',
    ),
  );
  write(
    'android/app/src/main/res/values/ic_launcher_background.xml',
    utf8.encode(
      '<?xml version="1.0" encoding="utf-8"?>\n'
      '<!-- Generated by tool/make_icons.dart. Do not edit. -->\n'
      '<resources>\n'
      '    <color name="ic_launcher_background">#${_hex(MarkSpec.fieldColor)}</color>\n'
      '</resources>\n',
    ),
  );

  // macOS and iOS: the sizes are whatever the generated asset catalogue asks
  // for, read back out of it rather than listed again here.
  //
  // The two want opposite things. macOS shows the icon as drawn, so it keeps
  // the rounded corners and sits inside Apple's margin. iOS masks the corners
  // itself and rejects any transparency at all, so its icons are square, edge
  // to edge, and written without an alpha channel.
  appleIcons('macos/Runner/Assets.xcassets/AppIcon.appiconset', write, macIcon);
  appleIcons('ios/Runner/Assets.xcassets/AppIcon.appiconset', write, iosIcon);

  // The tray. Bundled as a Flutter asset rather than a platform resource,
  // because tray_manager is handed a path at runtime and resolves it out of
  // the asset bundle.
  //
  // Windows and Linux get the mark as it appears everywhere else — the tray
  // icon sits beside the taskbar button and should be the same thing. macOS
  // gets a template instead: the menu bar recolours what it is given, so an
  // image that is not black-on-transparent comes out as a smudge on a dark
  // menu bar and a different smudge on a light one.
  write(
    'assets/tray/tray.ico',
    ico([for (final size in _trayIcoSizes) png(render(size), size, size)]),
  );
  write('assets/tray/tray.png', png(render(64), 64, 64));
  write('assets/tray/tray_template.png', trayTemplate(44));

  // For anywhere outside a build: a readme, a store listing, the platforms
  // that do not have a runner yet. The SVG is the one to hand to a designer.
  write('assets/icon/ddirc.png', png(render(512), 512, 512));
  write('assets/icon/ddirc.svg', utf8.encode(svg()));

  final names = written.keys.toList()..sort();
  for (final name in names) {
    stdout.writeln('  ${written[name]!.toString().padLeft(7)}  $name');
  }
  stdout.writeln('${written.length} files');
}

/// The macOS menu-bar image: the hash alone, in black, on transparency.
///
/// Marked as a template when it is handed to the tray, which is what lets the
/// system invert it for a dark menu bar and dim it when the bar is inactive.
/// A template's colour is discarded and only its alpha is read, so black here
/// is a convention rather than a choice of ink.
Uint8List trayTemplate(int size) => png(
  render(size, field: false, scale: _templateScale, glyph: 0xFF000000),
  size,
  size,
);

/// One macOS icon: rounded, inside Apple's margin, alpha kept.
Uint8List macIcon(int size) => png(render(size, scale: _macScale), size, size);

/// One iOS icon: square, edge to edge, and with no alpha channel at all.
Uint8List iosIcon(int size) => png(
  render(size, field: false, backdrop: MarkSpec.fieldColor),
  size,
  size,
  opaque: true,
);

/// Fill in an Xcode asset catalogue, at whatever sizes it asks for.
///
/// The catalogue is generated by `flutter create` and is the authority on which
/// files an Xcode build expects; restating that list here would be a second
/// copy to keep in step, and a missing icon in an asset catalogue is a build
/// warning that is easy to miss.
void appleIcons(
  String dir,
  void Function(String path, List<int> bytes) write,
  Uint8List Function(int size) draw,
) {
  final catalogue =
      jsonDecode(File('$dir/Contents.json').readAsStringSync())
          as Map<String, dynamic>;

  final wanted = <String, int>{};
  for (final entry
      in (catalogue['images'] as List).cast<Map<String, dynamic>>()) {
    final name = entry['filename'] as String?;
    if (name == null) continue;
    // "83.5x83.5" at "2x" is a 167-pixel file. The same file often appears
    // twice — 32 pixels is both 16pt@2x and 32pt@1x — hence a map.
    final points = double.parse((entry['size'] as String).split('x').first);
    final scale = int.parse((entry['scale'] as String).replaceAll('x', ''));
    wanted[name] = (points * scale).round();
  }

  for (final MapEntry(key: name, value: size) in wanted.entries) {
    write('$dir/$name', draw(size));
  }
}

String _hex(int argb) =>
    argb.toRadixString(16).padLeft(8, '0').substring(2).toUpperCase();

