/// The mark at [size] pixels square, as straight-alpha RGBA.
///
/// [field] draws the rounded square; without it only the glyph is drawn, on
/// transparency, which is what Android's adaptive foreground wants.
/// [scale] is how much of the canvas the mark occupies, centred.
/// [backdrop] fills the canvas edge to edge first, for iOS, which masks the
/// corners itself and will not accept an icon with any transparency in it.
/// [glyph] overrides the hash's colour, for the macOS menu-bar template, which
/// has to be a single opaque ink on transparency rather than the mark's own
/// near-white.
Uint8List render(
  int size, {
  bool field = true,
  double scale = 1,
  int? backdrop,
  int? glyph,
}) {
  final pixels = Uint8List(size * size * 4);
  final side = size * scale;
  final origin = (size - side) / 2;

  // Unit coordinates to pixels, at the centre of pixel (x, y).
  double px(double u) => origin + u * side;

  final radius = MarkSpec.corner * side;
  final half = side / 2;
  final centre = origin + half;
  final ink = MarkSpec.stroke * side / 2;

  for (var y = 0; y < size; y++) {
    for (var x = 0; x < size; x++) {
      final cx = x + 0.5;
      final cy = y + 0.5;

      var r = 0.0, g = 0.0, b = 0.0, a = 0.0;

      if (backdrop != null) {
        (r, g, b, a) = _over(backdrop, 1, r, g, b, a);
      }

      if (field) {
        final cover = _coverage(
          _roundedBox(cx - centre, cy - centre, half, half, radius),
        );
        (r, g, b, a) = _over(MarkSpec.fieldColor, cover, r, g, b, a);
      }

      // One distance for the whole glyph, so the four strokes do not blend
      // over one another where they cross.
      var d = double.infinity;
      for (final (x1, y1, x2, y2) in MarkSpec.strokes) {
        final ds = _segment(cx, cy, px(x1), px(y1), px(x2), px(y2), ink);
        if (ds < d) d = ds;
      }
      (r, g, b, a) = _over(
        glyph ?? MarkSpec.glyphColor,
        _coverage(d),
        r,
        g,
        b,
        a,
      );

      final i = (y * size + x) * 4;
      pixels[i] = (r * 255).round();
      pixels[i + 1] = (g * 255).round();
      pixels[i + 2] = (b * 255).round();
      pixels[i + 3] = (a * 255).round();
    }
  }
  return pixels;
}

/// A distance in pixels to how much of this pixel the shape covers.
///
/// The one-pixel ramp either side of the edge is the whole of the
/// antialiasing, and it is why the 16px icon is legible.
double _coverage(double distance) => (0.5 - distance).clamp(0.0, 1.0);

/// Signed distance to a rounded box centred on the origin.
double _roundedBox(double px, double py, double halfW, double halfH, double r) {
  final qx = px.abs() - halfW + r;
  final qy = py.abs() - halfH + r;
  final outside = math.sqrt(
    math.max(qx, 0) * math.max(qx, 0) + math.max(qy, 0) * math.max(qy, 0),
  );
  return math.min(math.max(qx, qy), 0) + outside - r;
}

/// Signed distance to a line from (ax, ay) to (bx, by), thickened by [r].
double _segment(
  double px,
  double py,
  double ax,
  double ay,
  double bx,
  double by,
  double r,
) {
  final pax = px - ax, pay = py - ay;
  final bax = bx - ax, bay = by - ay;
  final len = bax * bax + bay * bay;
  final h = len == 0 ? 0.0 : ((pax * bax + pay * bay) / len).clamp(0.0, 1.0);
  final dx = pax - bax * h, dy = pay - bay * h;
  return math.sqrt(dx * dx + dy * dy) - r;
}

/// Source-over compositing, in straight alpha.
(double, double, double, double) _over(
  int color,
  double alpha,
  double dr,
  double dg,
  double db,
  double da,
) {
  if (alpha <= 0) return (dr, dg, db, da);
  final sr = ((color >> 16) & 0xFF) / 255;
  final sg = ((color >> 8) & 0xFF) / 255;
  final sb = (color & 0xFF) / 255;
  final out = alpha + da * (1 - alpha);
  if (out <= 0) return (0, 0, 0, 0);
  double blend(double s, double d) => (s * alpha + d * da * (1 - alpha)) / out;
  return (blend(sr, dr), blend(sg, dg), blend(sb, db), out);
}

/// The same four strokes, as a vector file.
String svg() {
  final w = MarkSpec.stroke * 1000;
  final lines = [
    for (final (x1, y1, x2, y2) in MarkSpec.strokes)
      '  <line x1="${x1 * 1000}" y1="${y1 * 1000}" '
          'x2="${x2 * 1000}" y2="${y2 * 1000}" />',
  ].join('\n');

  return '<?xml version="1.0" encoding="UTF-8"?>\n'
      '<!-- Generated by tool/make_icons.dart from lib/src/ui/mark_spec.dart. -->\n'
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" '
      'width="1000" height="1000">\n'
      '  <rect width="1000" height="1000" rx="${MarkSpec.corner * 1000}" '
      'fill="#${_hex(MarkSpec.fieldColor)}" />\n'
      '  <g stroke="#${_hex(MarkSpec.glyphColor)}" stroke-width="$w" '
      'stroke-linecap="round">\n'
      '$lines\n'
      '  </g>\n'
      '</svg>\n';
}

