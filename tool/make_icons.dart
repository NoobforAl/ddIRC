/// An 8-bit PNG. [pixels] must be `width * height * 4` bytes of straight-alpha
/// RGBA; [opaque] drops the alpha channel, which is what the App Store demands
/// of an iOS icon and what Xcode warns about if you skip.
Uint8List png(Uint8List pixels, int width, int height, {bool opaque = false}) {
  // Every scanline gets filter type 0 (none). Filtering would compress a
  // photograph better; this is flat colour, which zlib already handles.
  final channels = opaque ? 3 : 4;
  final stride = width * channels;
  final raw = Uint8List(height * (stride + 1));
  for (var y = 0; y < height; y++) {
    var at = y * (stride + 1);
    raw[at++] = 0;
    for (var x = 0; x < width; x++) {
      final from = (y * width + x) * 4;
      raw[at++] = pixels[from];
      raw[at++] = pixels[from + 1];
      raw[at++] = pixels[from + 2];
      if (!opaque) raw[at++] = pixels[from + 3];
    }
  }

  final header = BytesBuilder()
    ..add(_be32(width))
    ..add(_be32(height))
    ..addByte(8) // bits per channel
    ..addByte(opaque ? 2 : 6) // colour type: RGB or RGBA
    ..addByte(0) // deflate
    ..addByte(0) // adaptive filtering
    ..addByte(0); // no interlace

  final file = BytesBuilder()
    ..add(const [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    ..add(_chunk('IHDR', header.toBytes()))
    ..add(_chunk('IDAT', ZLibEncoder(level: 9).convert(raw)))
    ..add(_chunk('IEND', const []));
  return file.toBytes();
}

/// An .ico wrapping already-encoded PNGs, largest last.
///
/// PNG-compressed entries rather than the old BMP ones: every Windows since
/// Vista reads them, and a 256px BMP entry alone would be 256 KB.
Uint8List ico(List<Uint8List> images) {
  final out = BytesBuilder()
    ..add(_le16(0)) // reserved
    ..add(_le16(1)) // type: icon
    ..add(_le16(images.length));

  var offset = 6 + images.length * 16;
  for (final image in images) {
    // The size comes back out of the PNG header rather than being passed in,
    // so the directory cannot end up describing a different image.
    final width = _readBe32(image, 16);
    out
      ..addByte(width >= 256 ? 0 : width) // 0 means 256
      ..addByte(width >= 256 ? 0 : width)
      ..addByte(0) // not a palette
      ..addByte(0) // reserved
      ..add(_le16(1)) // colour planes
      ..add(_le16(32)) // bits per pixel
      ..add(_le32(image.length))
      ..add(_le32(offset));
    offset += image.length;
  }
  for (final image in images) {
    out.add(image);
  }
  return out.toBytes();
}

List<int> _chunk(String type, List<int> data) {
  final body = BytesBuilder()
    ..add(ascii.encode(type))
    ..add(data);
  final bytes = body.toBytes();
  return [..._be32(data.length), ...bytes, ..._be32(_crc32(bytes))];
}

List<int> _be32(int v) => [
  (v >> 24) & 0xFF,
  (v >> 16) & 0xFF,
  (v >> 8) & 0xFF,
  v & 0xFF,
];

List<int> _le16(int v) => [v & 0xFF, (v >> 8) & 0xFF];

List<int> _le32(int v) => [
  v & 0xFF,
  (v >> 8) & 0xFF,
  (v >> 16) & 0xFF,
  (v >> 24) & 0xFF,
];

int _readBe32(List<int> bytes, int at) =>
    (bytes[at] << 24) |
    (bytes[at + 1] << 16) |
    (bytes[at + 2] << 8) |
    bytes[at + 3];

final _crcTable = List<int>.generate(256, (n) {
  var c = n;
  for (var k = 0; k < 8; k++) {
    c = (c & 1) != 0 ? 0xEDB88320 ^ (c >> 1) : c >> 1;
  }
  return c;
});

int _crc32(List<int> bytes) {
  var c = 0xFFFFFFFF;
  for (final byte in bytes) {
    c = _crcTable[(c ^ byte) & 0xFF] ^ (c >> 8);
  }
  return c ^ 0xFFFFFFFF;
}
